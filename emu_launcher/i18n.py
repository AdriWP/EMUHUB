"""Mehrsprachigkeit (Deutsch / English) ohne Zusatzpakete.

Benutzung:  tr("Speichern")                      -> "Speichern" bzw. "Save"
            tr("„{game}“ entfernt.", game=name)  -> mit Platzhaltern
Die deutschen Texte sind zugleich die Schlüssel. Fehlt eine englische Übersetzung,
wird der deutsche Text angezeigt. Neue Sprache: Eintrag in LANGUAGES + eigenes Wörterbuch.
"""
from __future__ import annotations

LANGUAGES: dict[str, str] = {"de": "Deutsch", "en": "English"}
DEFAULT_LANGUAGE = "en"   # neue Installationen starten auf Englisch (Deutsch in den Einstellungen wählbar)

_current = DEFAULT_LANGUAGE


def set_language(code: str) -> str:
    """Setzt die Sprache (unbekannte Codes -> Standardsprache) und gibt den aktiven Code zurück."""
    global _current
    _current = code if code in LANGUAGES else DEFAULT_LANGUAGE
    return _current


def get_language() -> str:
    return _current


def tr(text: str, **fmt) -> str:
    """Übersetzt `text` (deutscher Schlüssel). Mit Schlüsselwörtern werden {Platzhalter} ersetzt."""
    out = TRANSLATIONS.get(_current, {}).get(text, text)
    return out.format(**fmt) if fmt else out


